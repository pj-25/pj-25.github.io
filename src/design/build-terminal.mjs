export function buildTerminal(baseTree, terminalTree) {
  const tokens = flatten(merge(baseTree, terminalTree));
  const light = palette(tokens, 'light'); const dark = palette(tokens, 'dark');
  const checks = [...gates(light, 'light'), ...gates(dark, 'dark')];
  return { checks, files: { 'ghostty/pj-light': ghostty(light), 'ghostty/pj-dark': ghostty(dark), 'nvim/colors/pj.lua': nvim(light, dark) } };
}

function main() {
  const check = process.argv.includes('--check');
  const read = (n) => JSON.parse(readFileSync(join(HERE, 'tokens', n), 'utf8'));
  const { checks, files } = buildTerminal(read('base.tokens.json'), read('terminal.tokens.json'));
  for (const c of checks) console.log(`${c.ok ? 'ok  ' : 'FAIL'} ${c.theme.padEnd(5)} ${c.name.padEnd(10)} ${c.ratio} (min ${c.min})`);
  const problems = checks.filter((c) => !c.ok).map((c) => `contrast ${c.theme} ${c.name} = ${c.ratio} < ${c.min}`);
  for (const [rel, text] of Object.entries(files)) {
    const out = join(OUT, rel);
    if (check) { if (!existsSync(out) || readFileSync(out, 'utf8') !== text) problems.push(`${relative(process.cwd(), out)} is stale: run \`npm run terminal\``); }
    else if (!problems.length) { mkdirSync(dirname(out), { recursive: true }); writeFileSync(out, text); }
  }
  if (problems.length) { console.error(problems.map((p) => `✗ ${p}`).join('\n')); process.exit(1); }
  console.log(check ? '✓ terminal: up to date, contrast ok' : `✓ wrote ${Object.keys(files).length} files to ${relative(process.cwd(), OUT)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
