// Terminal identity (SPEC-003): DTCG tokens → Ghostty themes + a Neovim colorscheme, contrast-gated.
// Usage: node src/design/build-terminal.mjs [--check]
// Output: src/design/out/terminal/{ghostty/pj-light, ghostty/pj-dark, nvim/colors/pj.lua}
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { flatten, merge, resolve, colorHex, contrast } from './build-tokens.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'out', 'terminal');
const HEADER = 'GENERATED by src/design/build-terminal.mjs from src/design/tokens/*.tokens.json. Do not edit.';

/** Resolve one theme ('light' | 'dark') into a flat palette of #rrggbb strings. */
export function palette(tokens, theme) {
  const get = (k) => colorHex(resolve(tokens, `terminal.${theme}.${k}`).value);
  const p = { bg: get('background'), fg: get('foreground'), cursor: get('cursor'), selBg: get('selection-bg'),
    selFg: get('selection-fg'), surface: get('surface'), comment: get('comment'), ansi: [] };
  for (let i = 0; i < 16; i++) p.ansi.push(get(`ansi.${i}`));
  return p;
}

/** Contrast gates (R3). Returns a list of failures. */
export function gates(p, theme) {
  const need = [['foreground', p.fg, 4.5], ['comment', p.comment, 4.5]];
  for (const i of [1, 2, 3, 4, 5, 6, 9, 10, 11, 12, 13, 14]) need.push([`ansi ${i}`, p.ansi[i], 4.5]);
  if (theme === 'light') need.push(['ansi 7', p.ansi[7], 3], ['ansi 15', p.ansi[15], 3]);
  else need.push(['ansi 8', p.ansi[8], 3], ['ansi 7', p.ansi[7], 4.5], ['ansi 15', p.ansi[15], 4.5]);
  return need.map(([name, c, min]) => ({ theme, name, ratio: +contrast(c, p.bg).toFixed(2), min }))
    .map((r) => ({ ...r, ok: r.ratio >= r.min }));
}

export function ghostty(p) {
  return [`# ${HEADER}`, ...p.ansi.map((c, i) => `palette = ${i}=${c}`), `background = ${p.bg}`, `foreground = ${p.fg}`,
    `cursor-color = ${p.cursor}`, `cursor-text = ${p.bg}`, `selection-background = ${p.selBg}`, `selection-foreground = ${p.selFg}`, ''].join('\n');
}

